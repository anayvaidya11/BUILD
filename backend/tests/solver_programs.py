"""Room programs shaped like the planner's output (RoomProgram dicts), for solver tests.

Types are limited to schema.RoomType. requested_sqft defaults to room total / 0.88,
which is what PLAN_SYSTEM asks the planner to do.
"""


def R(rid, rtype, sqft, adj=(), name=None):
    return {"id": rid, "type": rtype, "name": name or rid.replace("_", " ").title(),
            "target_sqft": sqft, "adjacent_to": list(adj)}


def P(*rooms, requested=None, aspect=1.4):
    total = sum(r["target_sqft"] for r in rooms)
    return {"requested_sqft": requested or round(total / 0.88 / 10) * 10, "aspect_ratio": aspect,
            "notes": "", "rooms": list(rooms)}


